'use strict';
const fs=require('node:fs');
const assert=require('node:assert/strict');
const editor=fs.readFileSync('server/oilandgas/editor.js','utf8');
const member=fs.readFileSync('server/oilandgas/membership-admin.js','utf8');
const page=fs.readFileSync('server/oilandgas/desk/desk.html','utf8');
const ui=fs.readFileSync('server/oilandgas/desk/membership-admin.js','utf8');
const membership=fs.readFileSync('server/oilandgas/membership.js','utf8');
const guard=editor.indexOf("router.use(wrap(async(req,res,next)=>{");
const mount=editor.indexOf("router.use('/members', require('./membership-admin'))");
assert(guard>=0 && mount>guard,'Membership actions must be behind editor session auth.');
assert(member.includes("status:'pending',consent:true"),'Only consented pending applications can be approved.');
assert(member.includes("'welcomeMail.state':{$in:['queued','retry']}"),'Delivery worker must send only queued/retry emails.');
assert(member.includes("'welcomeMail.state':'sent'"),'SMTP accepted status should be recorded.');
assert(member.includes("Resend-Idempotency-Key"),'Delivery attempt must have stable idempotency key.');
assert(member.includes("OIL_ARTICLE_RESEND_KEY"),'Must reuse existing mail credentials.');
assert(member.includes("setImmediate(()=>deliverQueued()"),'Only explicit approval should trigger the mail workflow.');
assert(!membership.includes("sendMail("),'Public membership application must not send approval emails.');
assert(page.includes('id="membership-pending"') && page.includes('membership-admin.js?v=1'));
assert(ui.includes("confirm(") && ui.includes("api('/approve'"),'Approval requires editor confirmation.');
assert(!ui.includes("innerHTML"),'Never interpolate untrusted member fields as HTML.');
console.log('Membership approval workflow and access checks passed.');
